-- Knowledge base: a set of articles (title + body), each tracking when it was
-- created and when it was last edited.
--
-- No BEGIN/COMMIT here: `supabase db push` runs each migration file inside its
-- own transaction.

create table public.articles (
    id          bigint       generated by default as identity not null,
    title       text         not null,
    body        text         not null,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    constraint articles_pkey primary key (id)
) tablespace pg_default;

-- The knowledge base is listed newest-edited first.
create index articles_updated_at_idx on public.articles (updated_at desc);

-- updated_at is maintained by the database, so a caller that forgets to send
-- it cannot leave a stale "last edited" date behind, and one that sends a wrong
-- value cannot forge it.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

create trigger articles_set_updated_at
    before update on public.articles
    for each row
    execute function public.set_updated_at();